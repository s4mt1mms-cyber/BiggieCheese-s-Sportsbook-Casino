// Copies the code the game server shares with the web app into functions/lib/:
//   public/js/codec.js                      -> lib/codec.js   (Firestore value codec)
//   public/index.html  TH_PURE_START..END   -> lib/thpure.js  (Hold'em rules: evaluator, pots, betting, bot)
// The app and the server must agree on these exactly, so they are generated, never hand-edited.
//   node scripts/sync-shared.mjs          regenerate
//   node scripts/sync-shared.mjs --check  exit 1 if lib/ is out of date (CI runs this before deploying)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const lib = path.resolve(here, "../lib");
const check = process.argv.includes("--check");

const HDR = (src) => `// GENERATED by functions/scripts/sync-shared.mjs from ${src}. Do not edit; edit the source and re-run it.\n`;

const codec = HDR("public/js/codec.js") + fs.readFileSync(path.join(root, "public/js/codec.js"), "utf8");

const html = fs.readFileSync(path.join(root, "public/index.html"), "utf8");
const a = html.indexOf("/*TH_PURE_START*/"), b = html.indexOf("/*TH_PURE_END*/");
if (a < 0 || b < a) { console.error("TH_PURE markers not found in public/index.html"); process.exit(1); }
const pure = html.slice(a + "/*TH_PURE_START*/".length, b);
const names = [...pure.matchAll(/^(?:async\s+)?function\s+([A-Za-z0-9_]+)|^const\s+([A-Za-z0-9_]+)\s*=|,\s*(TH_RP)\s*=/gm)]
  .map((m) => m[1] || m[2] || m[3]).filter(Boolean);
const thpure = HDR("public/index.html (TH_PURE section)") + pure.trim() + "\n\nexport { " + [...new Set(names)].join(", ") + " };\n";

let stale = 0;
for (const [f, txt] of [["codec.js", codec], ["thpure.js", thpure]]) {
  const p = path.join(lib, f);
  const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
  if (cur === txt) continue;
  if (check) { console.error(`functions/lib/${f} is out of date: run node functions/scripts/sync-shared.mjs`); stale++; }
  else { fs.writeFileSync(p, txt); console.log("wrote functions/lib/" + f); }
}
if (stale) process.exit(1);
if (check) console.log("functions/lib is in sync with the app");
